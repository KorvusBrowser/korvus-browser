//! `install/dom_chain.rs` -- THE element factory: fill the wrapper-retype maps from the one tag table.
//!
//! `binding::protos::node_proto` retypes every cppgc node wrapper by nodeType, HTML tag, or SVG /
//! MathML local name through eight `OpState` maps, and this is the only thing that fills them. They
//! used to be written from JS in four places (`dom/08a-tag-protos.js`'s 82 `rt()` lines,
//! `09-postshells.js` for nodeType 9, `generated_shells.js` for `ShadowRoot`, `07-spine.js` for
//! `HTMLUnknownElement`) plus a hand list of the 52 plain `HTMLElement` tags; W5.0c replaced all of it
//! with the ONE data source `korvus_dom::tags` (generated by `tools/sync/gen_element_tags.py` from the
//! vendored Blink tag tables) and deleted the JS and the hand list. It is called at context creation,
//! after the spine tables and the registry have created the prototypes.
//!
//! W9.1 finished the job at both ends. The SVG half had a SECOND filler -- `op_install_svg_factory`
//! walking a generated `SVG_FACTORY` copy of `SVG_TAGS` -- and `install::live::html_image` hand-wrote
//! the `img` row; both are gone. And `MATHML_TAGS` had been generated since W9.1a and read by NOTHING,
//! so every `<math>` / `<mi>` on a page wore `HTMLUnknownElement` while the answer sat in the table --
//! the same defect the SVG half had before W5.0c, one namespace later.
//!
//! Idempotent: a second call re-inserts the same prototypes. An interface the table names but the realm
//! does not expose registers nothing and is reported in [`DomProtoFill::missing`]; a test that expects
//! the shipped bundle's surface asserts that list is empty.

use deno_core::v8;
use crate::binding::host_dom::{ElementProto, MathmlElementProto, MathmlTagProtos, NodeProtos, ShadowRootProto, SvgElementProto, SvgTagProtos, TagProtos, UnknownElementProto};
use crate::binding::protos::{get_prop, global_get};

/// What one fill registered, for the W5.0c test to assert against the tables' lengths.
#[derive(Debug, Default, PartialEq, Eq)]
pub struct DomProtoFill {
    /// nodeType entries registered (of [`NODE_TYPE_IFACES`]).
    pub node_types: usize,
    /// HTML tags registered (of `korvus_dom::tags::HTML_TAGS`).
    pub html_tags: usize,
    /// SVG local names registered (of `korvus_dom::tags::SVG_TAGS`).
    pub svg_tags: usize,
    /// MathML local names registered (of `korvus_dom::tags::MATHML_TAGS`).
    pub mathml_tags: usize,
    /// Interface names a table names that are not constructors on the global; nothing was registered
    /// for the tags that map to them.
    pub missing: Vec<&'static str>,
}

/// nodeType -> interface for the per-nodeType prototypes `node_proto` reads (elements go through
/// the tag maps). Shadow roots are checked before this map by `node_proto` (they reuse
/// `NodeKind::Document`, so nodeType cannot tell them apart).
///
/// THE 9 ROW IS A FALLBACK AND NOTHING SHOULD REACH IT. Its comment used to justify it with
/// "a `<template>`'s content is a fragment root that reuses the Document node kind", and that has not
/// been true since `Dom::ensure_template_content` started pushing `NodeKind::Fragment`: template
/// content is nodeType 11, in this engine and in headless Chrome 150 alike (measured 2026-09-12). What
/// actually reached it was every DOCUMENT root that is not the page's -- so
/// `createHTMLDocument("t").documentElement.parentNode` answered a `DocumentFragment`. Documents are
/// interned in the node cache under their arena root now (`core/dom/document.rs::intern_document`), so
/// `wrap_cached` hands out the Document itself and never asks this map. What is left for the row is an
/// arena Document node that no `JsDocument` was ever minted over, which is a bug wherever it happens;
/// answering DocumentFragment is a less wrong answer than leaving the wrapper on HTMLElement.prototype,
/// which is what deleting the row would do.
pub const NODE_TYPE_IFACES: &[(u32, &str)] = &[
    (3, "Text"),
    (4, "CDATASection"),
    (7, "ProcessingInstruction"),
    (8, "Comment"),
    (9, "DocumentFragment"),
    (10, "DocumentType"),
    // `document.createDocumentFragment()` / `new DocumentFragment()` mint `NodeKind::Fragment`, nodeType 11.
    (11, "DocumentFragment"),
];

fn note_missing(out: &mut DomProtoFill, iface: &'static str) {
    if !out.missing.contains(&iface) {
        out.missing.push(iface);
    }
}

/// `globalThis[iface].prototype`, or `None` when the realm has no such constructor.
fn proto_of<'s>(scope: &mut v8::PinScope<'s, '_>, iface: &str) -> Option<v8::Global<v8::Object>> {
    let ctor = global_get(scope, iface).and_then(|v| v8::Local::<v8::Object>::try_from(v).ok())?;
    let proto = get_prop(scope, ctor, "prototype").and_then(|v| v8::Local::<v8::Object>::try_from(v).ok())?;
    Some(v8::Global::new(scope, &proto))
}

/// Fill `NodeProtos`, `ShadowRootProto`, `UnknownElementProto`, `TagProtos`, `SvgTagProtos`,
/// `SvgElementProto`, `MathmlTagProtos` and `MathmlElementProto` from [`NODE_TYPE_IFACES`] and
/// `korvus_dom::tags`. Call once the prototypes exist.
pub fn fill_dom_protos(scope: &mut v8::PinScope) -> DomProtoFill {
    let mut out = DomProtoFill::default();
    let op_state = deno_core::JsRuntime::op_state_from(scope);

    for (nt, iface) in NODE_TYPE_IFACES {
        match proto_of(scope, iface) {
            Some(g) => {
                op_state.borrow().borrow::<NodeProtos>().0.borrow_mut().insert(*nt, g);
                out.node_types += 1;
            }
            None => note_missing(&mut out, iface),
        }
    }
    match proto_of(scope, "ShadowRoot") {
        Some(g) => *op_state.borrow().borrow::<ShadowRootProto>().0.borrow_mut() = Some(g),
        None => note_missing(&mut out, "ShadowRoot"),
    }
    match proto_of(scope, "HTMLUnknownElement") {
        Some(g) => *op_state.borrow().borrow::<UnknownElementProto>().0.borrow_mut() = Some(g),
        None => note_missing(&mut out, "HTMLUnknownElement"),
    }

    let any_lazy = crate::install::templates::has_lazy_globals(scope);
    // One lookup per interface, not per tag: 140 HTML tags name 76 interfaces.
    let mut cache: std::collections::HashMap<&'static str, Option<v8::Global<v8::Object>>> = std::collections::HashMap::new();
    for (tag, iface) in korvus_dom::tags::HTML_TAGS {
        // a page interface put lazily: reading it here would make it; its tags make it when an
        // element of one is wrapped (`protos::node_proto`)
        if any_lazy && crate::install::templates::lazy_here(scope, iface) {
            crate::install::templates::note_lazy_tag_iface(scope, iface);
            continue;
        }
        let hit = cache.entry(*iface).or_insert_with(|| proto_of(scope, iface)).clone();
        match hit {
            Some(g) => {
                // Keyed folded: the arena stores HTML tags lower-case.
                op_state.borrow().borrow::<TagProtos>().0.borrow_mut().insert(tag.to_ascii_lowercase(), g);
                out.html_tags += 1;
            }
            None => note_missing(&mut out, *iface),
        }
    }
    for (tag, iface) in korvus_dom::tags::SVG_TAGS {
        // a page interface put lazily: reading it here would make it; its tags make it when an
        // element of one is wrapped (`protos::node_proto`)
        if any_lazy && crate::install::templates::lazy_here(scope, iface) {
            crate::install::templates::note_lazy_tag_iface(scope, iface);
            continue;
        }
        let hit = cache.entry(*iface).or_insert_with(|| proto_of(scope, iface)).clone();
        match hit {
            Some(g) => {
                // Exact case: SVG local names are case-sensitive (`clipPath`, `feBlend`).
                op_state.borrow().borrow::<SvgTagProtos>().0.borrow_mut().insert((*tag).to_string(), g);
                out.svg_tags += 1;
            }
            None => note_missing(&mut out, *iface),
        }
    }
    for (tag, iface) in korvus_dom::tags::MATHML_TAGS {
        // a page interface put lazily: reading it here would make it; its tags make it when an
        // element of one is wrapped (`protos::node_proto`)
        if any_lazy && crate::install::templates::lazy_here(scope, iface) {
            crate::install::templates::note_lazy_tag_iface(scope, iface);
            continue;
        }
        let hit = cache.entry(*iface).or_insert_with(|| proto_of(scope, iface)).clone();
        match hit {
            Some(g) => {
                // Exact case, like SVG: MathML is foreign content, so `annotation-xml` keeps its
                // spelling where an HTML tag would be folded.
                op_state.borrow().borrow::<MathmlTagProtos>().0.borrow_mut().insert((*tag).to_string(), g);
                out.mathml_tags += 1;
            }
            None => note_missing(&mut out, *iface),
        }
    }
    // The two namespace MISS paths, each its table's own `fallbackJSInterfaceName`: an SVG- or
    // MathML-namespaced tag with no interface of its own is `SVGElement` / `MathMLElement`, never
    // `HTMLUnknownElement`. Both measured on headless Chrome 150 on this machine
    // (`createElementNS(ns, "zzznotatag")`).
    match proto_of(scope, "SVGElement") {
        Some(g) => *op_state.borrow().borrow::<SvgElementProto>().0.borrow_mut() = Some(g),
        None => note_missing(&mut out, "SVGElement"),
    }
    match proto_of(scope, "MathMLElement") {
        Some(g) => *op_state.borrow().borrow::<MathmlElementProto>().0.borrow_mut() = Some(g),
        None => note_missing(&mut out, "MathMLElement"),
    }
    // No namespace, or a foreign one: `Element` itself.
    match proto_of(scope, "Element") {
        Some(g) => *op_state.borrow().borrow::<ElementProto>().0.borrow_mut() = Some(g),
        None => note_missing(&mut out, "Element"),
    }
    out
}
