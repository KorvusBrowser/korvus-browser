//! `binding::exposure` — the `[Exposed]` analog: how an interface's native registration reaches the
//! `extension!`, without a central hand-maintained list (REFACTOR-BLUEPRINT STEP 4, the "biggest win";
//! ARCHITECTURE Step 3's `registry.rs`).
//!
//! # The problem this removes
//!
//! Registration used to be one line in `bindings.rs`: `ops = [op_a, op_b, … 463 symbols]`, 9,061 bytes
//! on a single line, plus `objects = [… 40 cppgc types]`. Every interface that gained an op had to edit
//! that one line, so N agents working on N different interfaces all collided there. It was the single
//! hard blocker on parallel campaign work — a file-move or a new interface cannot be done concurrently
//! while membership lives in a bottleneck registry.
//!
//! Blink's answer is that exposure is *declarative, per-interface, and generated*: each `.idl` carries
//! its own `[Exposed=…]` and the compiler emits the per-context install table. There is no central list.
//!
//! # How this works
//!
//! Each interface file declares the ops it owns, right next to them:
//!
//! ```ignore
//! // src/core/messaging/message_port.rs — at the bottom, beside the ops themselves
//! crate::webapi_ops![op_mp_remote, op_port_deliver_external];
//! ```
//!
//! That expands to a module-private `__webapi_ops()`. `build.rs` walks `src/`, finds every file whose
//! text contains the macro, maps its path to a module path, and emits an OUT_DIR registry that calls
//! each one. `lib.rs` `include!`s that registry; the `extension!` consumes it through deno_core's own
//! `ops_fn` / `customizer` hooks. So:
//!
//! - **Adding an op touches only the file that defines it.** No shared line, no merge conflict.
//! - **The list cannot drift**, because it is rebuilt from the tree on every `cargo build`.
//!
//! # Why the macro, and not a `#[op2]` scan
//!
//! Ops are not all written as `#[op2] fn …` — local `macro_rules!` used to generate 58 of the 463
//! there once were (`node_getter!`, `doc_getter!`, `coll_op!` and six more). A build-time scanner
//! would have to understand every such macro and would silently drop an op the day someone adds one
//! more — and a dropped op is not a compile error, it is a member that vanishes from the JS surface at
//! runtime. An explicit per-file declaration is scannable with one literal token and cannot be
//! misparsed. `tests/registry.rs` pins the count so a dropped declaration fails the build, not the browser.
//!
//! That population has collapsed since: the JS shell layer those ops served is gone, and the sweeps
//! that followed it (W11.4–6) deleted every op nothing called. `node_getter!` and
//! its siblings in `core/dom/shared.rs` now emit only the raw v8 callback an `interface!` row names.
//!
//! # Why not `linkme`/`inventory`
//!
//! Link-time collection reads better, but `korvus-webapi` is an **rlib**: once the central list is gone,
//! nothing references the interface modules by name, and an unreferenced object file is exactly what a
//! linker is entitled to drop. That failure mode is silent and platform-dependent. Codegen has neither
//! property, and it is what ARCHITECTURE Step 3 already specifies ("generate `registry.rs` — the
//! op-registration aggregation — the one shared file that would otherwise contend").

use deno_core::OpDecl;

/// Declare the native ops this module contributes to the webapi extension.
///
/// Place it in the file that DEFINES the ops (visibility is module-local, so private `#[op2] fn`s work
/// without being made `pub(crate)` — 39 of them are). One invocation per file; `build.rs` finds the file
/// by this macro's name and wires `__webapi_ops()` into the generated registry.
#[macro_export]
macro_rules! webapi_ops {
    ($($op:path),* $(,)?) => {
        /// The ops this module contributes. Called by the OUT_DIR registry `build.rs` emits; never
        /// call it directly. (Generated by `crate::webapi_ops!`.)
        pub(crate) fn __webapi_ops() -> ::std::vec::Vec<::deno_core::OpDecl> {
            ::std::vec![$( $op() ),*]
        }
    };
}

// `webapi_objects!` WAS HERE: the cppgc-objects half of this registry, which fed deno_core's `objects =` list
// through the extension's `customizer`. Every class is an own class (`#[webapi(own)]`,
// `binding::class`), so nothing declares one and the half is deleted with its last user.

// The generated registry: `collected_ops()`, one call per declaring module.
// Rebuilt from the source tree on every `cargo build` (see build.rs) — never hand-edit, never commit.
include!(concat!(env!("OUT_DIR"), "/webapi_registry.rs"));

/// Every op declared anywhere in the crate — the `ops_fn` deno_core calls while building the extension.
///
/// deno_core expands `ops_fn = ops` to `ext.ops.to_mut().extend(ops())`, so this is the supported hook
/// rather than a post-hoc mutation of a built `Extension`.
pub(crate) fn ops() -> Vec<OpDecl> {
    collected_ops()
}

/// The names of every registered op, for duplicate detection in `tests/registry.rs`. The `OpDecl`s
/// themselves stay crate-private — only deno_core should consume those.
pub fn registered_op_names() -> Vec<&'static str> {
    ops().iter().map(|o| o.name).collect()
}

/// The number of ops actually registered.
pub fn registered_counts() -> usize {
    ops().len()
}

/// The module paths that declared ops (sorted), for the manifest gate in `tests/registry.rs` -- so a lost
/// declaration is reported by NAME, not as a count that moved.
pub fn declaring_module_names() -> &'static [&'static str] {
    DECLARING_OP_MODULES
}

