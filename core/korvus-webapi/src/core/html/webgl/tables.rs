//! The four WebGL `interface!` tables — the DATA half of `webgl.rs`.
//!
//! WHY THE ROWS LIVE IN THEIR OWN FILE. `WebGLRenderingContext` and `WebGL2RenderingContext` are
//! 740 and 1,350 rows, and 1,416 of those 2,090 are numeric CONSTANTS the capture recorded twice
//! each (WebIDL puts a constant on the interface object AND on the prototype). They are data, not
//! implementation, and `webgl.rs` is the implementation: the recorder, the 203 draw-call bodies and
//! the four oracle-backed reads. One file for each, and `interface!` still gives every one of these
//! interfaces exactly ONE definition site (invariant I1) — which is the point of the rule, not which
//! file it sits in.
//!
//! EVERY ROW WAS DERIVED FROM THE `InterfaceDef` IT REPLACES, mechanically: the same names in the
//! same order, the same `length` and `required`, the same `enumerable`/`configurable`/`nullable`,
//! and every constant's value copied verbatim. So `Object.getOwnPropertyNames(WebGLRenderingContext
//! .prototype)` is the capture's list in the capture's order by construction, and
//! `core/korvus-runtime/tests/webgl_live.rs` asserts exactly that against the bundle.
//!
//! The bodies:
//!   * `install_webgl_context` — `canvas` and the drawing-buffer reads, the 203 recorded draw calls
//!     (one generic callback keyed on the row's NAME), and the four oracle-backed reads
//!     (`getParameter` / `getExtension` / `getSupportedExtensions` / `getContextAttributes`), whose
//!     v1 and v2 forms are told apart by the row's own label.
//!   * `stub` — 4 v1 and 19 v2 methods this engine does not record yet (the compressed-texture and
//!     buffer-copy families). Honest and counted, exactly as they were.

