/// Every string literal in `src` that the compiler will actually build into the library, as
/// `(1-based line, source text between the quotes)`.
///
/// Skipped, and why each matters here:
/// * `//`, `///`, `//!` and nested `/* */` comments -- **a comment is not a definition**. W9.24 hit the
///   other side of this twice in one unit: `freeze.sh`'s `ratchets()` greps whole files, so documenting
///   the removal of a JS string, in that string's own syntax, put the counter straight back up. That
///   asymmetry silently punishes writing down what you removed.
/// * `'a'` char literals and `'a` lifetimes, so an apostrophe in either cannot open a phantom string.
/// * raw strings, `r"..."` through `r####"..."####`, and byte strings -- the kernel's biggest JS string
///   (`engine.rs`'s BOOTSTRAP) is a raw string, and a scanner that does not know the form would either
///   miss it or mis-parse every `\` in it.
/// * `#[cfg(test)]` items, whole. Such a string is never compiled into the library, and the JS in them
///   is measurement -- `Object.getPrototypeOf(DOMRect.prototype) === DOMRectReadOnly.prototype` asked of
///   the live engine, which is how this project proves things. 695 of the tree's 34 899 literals.
fn string_literals(src: &str) -> Vec<(usize, String)> {
    let b = src.as_bytes();
    let n = b.len();
    let (mut i, mut line) = (0usize, 1usize);
    let mut out = Vec::new();
    // `#[cfg(test)]` seen, waiting for the item it attributes.
    let mut pending_test = false;
    let mut depth: i32 = 0;
    // brace depth at which the current `#[cfg(test)]` item opened, if we are inside one.
    let mut test_depth: Option<i32> = None;

    while i < n {
        match b[i] {
            b'\n' => {
                line += 1;
                i += 1;
            }
            b'{' => {
                depth += 1;
                if pending_test {
                    if test_depth.is_none() {
                        test_depth = Some(depth - 1);
                    }
                    pending_test = false;
                }
                i += 1;
            }
            b'}' => {
                depth -= 1;
                if test_depth == Some(depth) {
                    test_depth = None;
                }
                i += 1;
            }
            b';' if pending_test => {
                // `#[cfg(test)] use ...;` -- an item with no block.
                pending_test = false;
                i += 1;
            }
            b'/' if i + 1 < n && b[i + 1] == b'/' => {
                while i < n && b[i] != b'\n' {
                    i += 1;
                }
            }
            b'/' if i + 1 < n && b[i + 1] == b'*' => {
                let mut nest = 1;
                i += 2;
                while i < n && nest > 0 {
                    if b[i] == b'\n' {
                        line += 1;
                    }
                    if i + 1 < n && b[i] == b'/' && b[i + 1] == b'*' {
                        nest += 1;
                        i += 2;
                    } else if i + 1 < n && b[i] == b'*' && b[i + 1] == b'/' {
                        nest -= 1;
                        i += 2;
                    } else {
                        i += 1;
                    }
                }
            }
            b'#' if src[i..].starts_with("#[cfg(test)]") => {
                pending_test = true;
                i += "#[cfg(test)]".len();
            }
            b'\'' => {
                // char literal or lifetime
                let mut j = i + 1;
                if j < n && b[j] == b'\\' {
                    j += 2;
                    while j < n && b[j] != b'\'' && b[j] != b'\n' {
                        j += 1;
                    }
                    i = if j < n && b[j] == b'\'' { j + 1 } else { i + 1 };
                } else {
                    // one char then a closing quote => char literal; otherwise a lifetime
                    let c_end = src[i + 1..].chars().next().map(|c| i + 1 + c.len_utf8()).unwrap_or(i + 1);
                    i = if c_end < n && b[c_end] == b'\'' { c_end + 1 } else { i + 1 };
                }
            }
            _ => {
                if let Some((text, end, nl)) = read_string(src, i) {
                    if test_depth.is_none() {
                        out.push((line, text));
                    }
                    line += nl;
                    i = end;
                } else {
                    // Advance a whole character: every `src[i..]` above needs `i` on a boundary.
                    i += src[i..].chars().next().map(char::len_utf8).unwrap_or(1);
                }
            }
        }
    }
    out
}

/// A string literal starting at or just before `i`: `"…"`, `b"…"`, `r"…"`, `br##"…"##`. Returns the
/// source text between the delimiters, the index just past the literal, and the newlines it spans.
fn read_string(src: &str, i: usize) -> Option<(String, usize, usize)> {
    let b = src.as_bytes();
    let n = b.len();
    let mut p = i;
    // A prefix is only a prefix when it is not the tail of an identifier (`str"` never happens, but
    // `foo.r` + `"` would, and `char"` must not read as a raw string).
    let prefixed = |p: usize, lit: &str| -> bool {
        src[p..].starts_with(lit) && (p == 0 || !is_word(b[p - 1]))
    };
    if prefixed(p, "br") || prefixed(p, "r") {
        let skip = if prefixed(p, "br") { 2 } else { 1 };
        let q = p + skip;
        let mut h = q;
        while h < n && b[h] == b'#' {
            h += 1;
        }
        if h < n && b[h] == b'"' {
            let hashes = h - q;
            let start = h + 1;
            let term = format!("\"{}", "#".repeat(hashes));
            let end = src[start..].find(&term).map(|r| start + r).unwrap_or(n);
            let text = src[start..end].to_string();
            let nl = text.matches('\n').count();
            return Some((text, (end + term.len()).min(n), nl));
        }
        p = i;
    }
    // A `b"…"` byte string opens one byte later, and the `b` is its own opener -- do not then ask
    // whether the character before the quote is a word character, because it is the `b`.
    let opens = if prefixed(p, "b\"") {
        p += 1;
        true
    } else {
        p < n && b[p] == b'"' && (p == 0 || !is_word(b[p - 1]))
    };
    if opens {
        let start = p + 1;
        let mut j = start;
        while j < n {
            match b[j] {
                b'\\' => j += 2,
                b'"' => break,
                _ => j += 1,
            }
        }
        let end = j.min(n);
        let text = src[start..end].to_string();
        let nl = text.matches('\n').count();
        return Some((text, (end + 1).min(n), nl));
    }
    None
}

