/// A marker is a shape that is SYNTAX in JavaScript: an operator applied to an operand, a keyword
/// applied to an expression, a call in statement position. A bare keyword or a bare identifier is
/// deliberately NOT a marker -- this tree is full of both, and reading them as source is how a
/// detector starts crying wolf. `browsing_context.rs` holds `"return"`, `"typeof"` and forty-one more
/// as a reserved-word table for its own tokenizer; four interface tables name a member
/// `"[Symbol.iterator]"`; `korvus-page` ships CSS with `url(a), local(b)` in it; `coherence.rs` says
/// `navigator.platform={plat:?}` in an error message. None of those are JavaScript and none are
/// flagged, because each marker below demands a second token.
const MARKERS: &[(&str, fn(&str) -> bool)] = &[
    ("arrow", |s| s.contains("=>")),
    ("strict-eq", |s| s.contains("===") || s.contains("!==")),
    ("function-kw", m_function),
    ("globalThis", m_global_this),
    ("declaration", m_declaration),
    ("return", m_return),
    ("typeof", m_typeof),
    ("new-ctor", m_new_ctor),
    ("prototype", m_prototype),
    ("try-catch", m_try_catch),
    ("object-static", |s| m_static_call(s, "Object")),
    ("reflect-static", |s| m_static_call(s, "Reflect")),
    ("symbol-call", m_symbol_for),
    ("await", m_await),
    ("class-decl", m_class_decl),
    ("dom-call", m_dom_call),
    ("this-member", m_this_member),
    ("deno-core", m_deno_core),
    ("member-call", m_member_call),
    ("control-flow", m_control_flow),
    ("call-stmt", m_call_stmt),
    ("member-assign", m_member_assign),
    ("index-assign", m_index_assign),
    ("block-open", m_block_open),
    ("es-module", m_es_module),
];

fn js_markers(s: &str) -> Vec<&'static str> {
    MARKERS.iter().filter(|(_, f)| f(s)).map(|(n, _)| *n).collect()
}

fn is_word(b: u8) -> bool {
    b.is_ascii_alphanumeric() || b == b'_' || b == b'$'
}
/// A keyword occurrence must not be glued to an identifier on either side, and must not be the tail of
/// a hyphenated CSS identifier (`@position-try {name}` is not a `try` block).
fn word_start(b: &[u8], i: usize) -> bool {
    i == 0 || !(is_word(b[i - 1]) || b[i - 1] == b'-')
}
fn word_end(b: &[u8], i: usize) -> bool {
    i >= b.len() || !is_word(b[i])
}
fn ws(b: &[u8], mut i: usize) -> usize {
    while i < b.len() && (b[i] as char).is_whitespace() {
        i += 1;
    }
    i
}
/// Advance past an identifier; returns None when there is none.
fn ident(b: &[u8], i: usize) -> Option<usize> {
    if i >= b.len() || b[i].is_ascii_digit() || !is_word(b[i]) {
        return None;
    }
    let mut j = i;
    while j < b.len() && is_word(b[j]) {
        j += 1;
    }
    Some(j)
}
fn at(b: &[u8], i: usize, c: u8) -> bool {
    i < b.len() && b[i] == c
}
fn one_of(b: &[u8], i: usize, set: &[u8]) -> bool {
    i < b.len() && set.contains(&b[i])
}
/// Every occurrence of `kw` as a whole word, offered to `f` as the index just past it.
fn each_kw(s: &str, kw: &str, mut f: impl FnMut(&[u8], usize) -> bool) -> bool {
    let b = s.as_bytes();
    let mut from = 0;
    while let Some(rel) = s[from..].find(kw) {
        let i = from + rel;
        let end = i + kw.len();
        if word_start(b, i) && word_end(b, end) && f(b, end) {
            return true;
        }
        from = i + 1;
    }
    false
}

fn m_function(s: &str) -> bool {
    each_kw(s, "function", |b, e| {
        let mut i = ws(b, e);
        if at(b, i, b'*') {
            i = ws(b, i + 1);
        }
        if let Some(j) = ident(b, i) {
            i = ws(b, j);
        }
        at(b, i, b'(')
    })
}
fn m_global_this(s: &str) -> bool {
    each_kw(s, "globalThis", |b, e| {
        let i = ws(b, e);
        one_of(b, i, b".[")
    })
}
fn m_declaration(s: &str) -> bool {
    ["const", "let", "var"].iter().any(|kw| {
        each_kw(s, kw, |b, e| {
            let i = ws(b, e);
            i > e && ident(b, i).is_some()
        })
    })
}
fn m_return(s: &str) -> bool {
    each_kw(s, "return", |b, e| {
        let i = ws(b, e);
        if at(b, i, b';') {
            return true;
        }
        one_of(b, i, b"({[\"'`+!-") || (i > e && ident(b, i).is_some())
    })
}
fn m_typeof(s: &str) -> bool {
    each_kw(s, "typeof", |b, e| {
        let i = ws(b, e);
        (i > e && ident(b, i).is_some()) || one_of(b, i, b"([\"'")
    })
}
fn m_new_ctor(s: &str) -> bool {
    each_kw(s, "new", |b, e| {
        let i = ws(b, e);
        if i == e || !(i < b.len() && b[i].is_ascii_uppercase()) {
            return false;
        }
        let Some(j) = ident(b, i) else { return false };
        at(b, ws(b, j), b'(')
    })
}
/// `.prototype` used as a value, not the English word: something must be done to it.
fn m_prototype(s: &str) -> bool {
    let b = s.as_bytes();
    let mut from = 0;
    while let Some(rel) = s[from..].find(".prototype") {
        let i = from + rel;
        let e = i + ".prototype".len();
        if word_end(b, e) && one_of(b, ws(b, e), b".[)=,;") {
            return true;
        }
        from = i + 1;
    }
    false
}
fn m_try_catch(s: &str) -> bool {
    ["try", "catch", "finally"].iter().any(|kw| each_kw(s, kw, |b, e| one_of(b, ws(b, e), b"({")))
}
fn m_static_call(s: &str, obj: &str) -> bool {
    each_kw(s, obj, |b, e| {
        if !at(b, e, b'.') {
            return false;
        }
        let Some(j) = ident(b, e + 1) else { return false };
        at(b, ws(b, j), b'(')
    })
}
fn m_symbol_for(s: &str) -> bool {
    each_kw(s, "Symbol", |b, e| {
        if !s_at(b, e, ".for") {
            return false;
        }
        at(b, ws(b, e + 4), b'(')
    })
}
fn s_at(b: &[u8], i: usize, lit: &str) -> bool {
    b.len() >= i + lit.len() && &b[i..i + lit.len()] == lit.as_bytes()
}
fn m_await(s: &str) -> bool {
    each_kw(s, "await", |b, e| {
        let i = ws(b, e);
        i > e && (ident(b, i).is_some() || one_of(b, i, b"([{"))
    })
}
fn m_class_decl(s: &str) -> bool {
    each_kw(s, "class", |b, e| {
        let i = ws(b, e);
        let Some(j) = ident(b, i) else { return false };
        let mut k = ws(b, j);
        if s_at(b, k, "extends") {
            k = ws(b, k + 7);
            while k < b.len() && (is_word(b[k]) || b[k] == b'.') {
                k += 1;
            }
            k = ws(b, k);
        }
        at(b, k, b'{')
    })
}
fn m_dom_call(s: &str) -> bool {
    const NAMES: &[&str] = &[
        "addEventListener",
        "removeEventListener",
        "dispatchEvent",
        "querySelector",
        "createElement",
        "postMessage",
        "importScripts",
    ];
    NAMES.iter().any(|n| each_kw(s, n, |b, e| at(b, ws(b, e), b'(')))
}
fn m_this_member(s: &str) -> bool {
    each_kw(s, "this", |b, e| at(b, e, b'.') && ident(b, e + 1).is_some())
}
fn m_deno_core(s: &str) -> bool {
    each_kw(s, "Deno", |b, e| s_at(b, e, ".core."))
}
/// `receiver.method(` -- a call on an object. The method name must start lower-case, which keeps
/// `Failed to construct 'X'` style prose and `Foo.Bar(` type paths out.
fn m_member_call(s: &str) -> bool {
    let b = s.as_bytes();
    let mut i = 0;
    while i < b.len() {
        let Some(idn) = ident(b, i) else {
            i += 1;
            continue;
        };
        if word_start(b, i) && at(b, idn, b'.') {
            if let Some(m) = ident(b, idn + 1) {
                if b[idn + 1].is_ascii_lowercase() && at(b, ws(b, m), b'(') {
                    return true;
                }
            }
        }
        i = idn.max(i + 1);
    }
    false
}
fn m_control_flow(s: &str) -> bool {
    ["if", "for", "while", "switch"].iter().any(|kw| {
        each_kw(s, kw, |b, e| {
            let i = ws(b, e);
            at(b, i, b'(') && !at(b, i + 1, b')')
        })
    })
}
/// A call in STATEMENT position: `fire('install');` at the start of a statement. The statement-start
/// requirement is what keeps CSS out -- `background: url(x);` is a call in value position.
fn m_call_stmt(s: &str) -> bool {
    let b = s.as_bytes();
    let mut i = 0;
    loop {
        let start = ws(b, i);
        if start >= b.len() {
            return false;
        }
        // only at a statement boundary
        if !(i == 0 || one_of(b, i.saturating_sub(1), b";{}\n")) {
            // advance to the next boundary
            match b[i..].iter().position(|c| matches!(c, b';' | b'{' | b'}' | b'\n')) {
                Some(p) => {
                    i += p + 1;
                    continue;
                }
                None => return false,
            }
        }
        if let Some(j) = ident(b, start) {
            let k = ws(b, j);
            if at(b, k, b'(') {
                // `( ... )` with no nested parens, then `;`
                if let Some(close) = b[k + 1..].iter().position(|c| matches!(c, b'(' | b')')) {
                    if b[k + 1 + close] == b')' && at(b, ws(b, k + close + 2), b';') {
                        return true;
                    }
                }
            }
        }
        match b[i..].iter().position(|c| matches!(c, b';' | b'{' | b'}' | b'\n')) {
            Some(p) => i += p + 1,
            None => return false,
        }
    }
}
/// `x.y = <expr>;` -- an assignment to a member, ended. The terminator is what separates it from
/// prose that merely NAMES a member, like `UA is {os} but navigator.platform={plat:?}`.
fn m_member_assign(s: &str) -> bool {
    let b = s.as_bytes();
    let mut i = 0;
    while i < b.len() {
        if b[i] == b'.' && i > 0 && (is_word(b[i - 1]) || b[i - 1] == b')' || b[i - 1] == b']') {
            if let Some(j) = ident(b, i + 1) {
                let k = ws(b, j);
                if at(b, k, b'=') && !at(b, k + 1, b'=') && assigned_expr_ends(b, k + 1) {
                    return true;
                }
            }
        }
        i += 1;
    }
    false
}
/// `obj[expr] = <expr>;` -- BOOTSTRAP's own shape (`globalThis[name] = ...`), the one the old rule's
/// `globalThis\.` could not see.
fn m_index_assign(s: &str) -> bool {
    let b = s.as_bytes();
    let mut i = 0;
    while i < b.len() {
        if b[i] == b'[' {
            if let Some(rel) = b[i + 1..].iter().position(|c| matches!(c, b']' | b'\n')) {
                let close = i + 1 + rel;
                if b[close] == b']' && close > i + 1 {
                    let k = ws(b, close + 1);
                    if at(b, k, b'=') && !at(b, k + 1, b'=') && assigned_expr_ends(b, k + 1) {
                        return true;
                    }
                }
            }
        }
        i += 1;
    }
    false
}
/// The right-hand side of an assignment runs to a `;` on the same line, with no second `=` in it.
fn assigned_expr_ends(b: &[u8], from: usize) -> bool {
    let mut i = from;
    let mut seen = false;
    while i < b.len() {
        match b[i] {
            b';' => return seen,
            b'=' | b'\n' => return false,
            c if !(c as char).is_whitespace() => seen = true,
            _ => {}
        }
        i += 1;
    }
    false
}
/// `) {` at end of line: a function, method or block header. Not a shape CSS or prose produces.
fn m_block_open(s: &str) -> bool {
    let b = s.as_bytes();
    let mut i = 0;
    while i < b.len() {
        if b[i] == b')' {
            let j = ws(b, i + 1);
            if at(b, j, b'{') {
                let k = j + 1;
                let mut k2 = k;
                while k2 < b.len() && (b[k2] == b' ' || b[k2] == b'\t' || b[k2] == b'\r') {
                    k2 += 1;
                }
                if k2 >= b.len() || b[k2] == b'\n' {
                    return true;
                }
            }
        }
        i += 1;
    }
    false
}
fn m_es_module(s: &str) -> bool {
    let imported = each_kw(s, "import", |b, e| {
        let i = ws(b, e);
        if one_of(b, i, b"({\"'") {
            return true;
        }
        if i == e {
            return false;
        }
        // `import X from "..."` / `import * as X from "..."` / `import { A, B } from "..."`
        let line_end = b[i..].iter().position(|c| *c == b'\n').map(|p| i + p).unwrap_or(b.len());
        let rest = &s[i..line_end];
        match rest.find(" from ") {
            Some(p) => {
                let q = ws(b, i + p + " from ".len());
                one_of(b, q, b"\"'")
            }
            None => false,
        }
    });
    imported
        || each_kw(s, "export", |b, e| {
            let i = ws(b, e);
            if i == e {
                return at(b, e, b'{');
            }
            at(b, i, b'{')
                || ["default", "function", "class", "const", "let", "var"].iter().any(|k| s_at(b, i, k) && word_end(b, i + k.len()))
        })
}

