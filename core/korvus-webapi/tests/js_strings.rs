//! The kernel's JavaScript inventory -- every Rust string literal under `core/*/src` that is
//! JavaScript, each one listed with a reason.
//!
//! WHY THIS REPLACES A REGEX. `scripts/freeze.sh` rule 3 existed to stop new Web API being defined in a
//! Rust string literal, and it detected exactly one shape:
//!
//! ```text
//! Object\.defineProperty\(|globalThis\.[A-Z][A-Za-z]+ *=
//! ```
//!
//! Measured against the only two JS strings this kernel has ever actually held, it scored **zero on
//! both**. `worker.rs`'s `SW_PRELUDE` defined `ev.request =`, `ev.respondWith =`, `ev.waitUntil =` --
//! instance properties, never a global. `engine.rs`'s `BOOTSTRAP` assigns `globalThis[name] = ...` in
//! BRACKET notation, and the pattern requires a dot. A rule that has never caught an instance of the
//! class it forbids is not a rule; and both strings were being deleted, which would have left it with
//! nothing at all to fail on. `the_shapes_freeze_rule_3_could_not_see` below is those two strings, kept
//! as a permanent negative control: it asserts this detector finds them AND that the old regex did not.
//!
//! WHY NOT A BROADER REGEX. The old rule enumerated FORMS OF ASSIGNMENT, and the forms are unbounded:
//! `obj.x =`, `obj["x"] =`, `Object.assign`, `Reflect.defineProperty`, a destructuring assignment, a
//! class body, a `Proxy`. Each patch invites the next miss, and a rule that is 80 % right is worse than
//! one honest about its scope, because people trust it. So the question is inverted: the kernel should
//! contain approximately zero JavaScript, and every exception is NAMED. Same shape as
//! `core/korvus-runtime/tests/fixtures/second_writers.manifest` and `scripts/freeze.baseline`, and it
//! fails in BOTH directions -- an unlisted JS string is a violation, and a listed one that has
//! disappeared is a stale inventory.
//!
//! WHY A RUST TEST AND NOT A SHELL GREP. Three things a line-oriented grep cannot do and this does:
//! it sees STRING LITERALS rather than lines (so a `//` inside `"https://..."` is not a comment, and a
//! comment is never a definition); it handles raw strings (`r#"..."#`), byte strings, char literals and
//! lifetimes; and it can skip `#[cfg(test)]` items, which never compile into the library at all. W9.24
//! declined to teach `freeze.sh`'s `ratchets()` to find `#[cfg(test)]` regions for exactly the right
//! reason -- in shell that rule is fragile. In a lexer it is not: it is brace depth.
//!
//! WHAT COUNTS AS JAVASCRIPT -- and what this gets wrong. See `MARKERS`. Measured on the tree at
//! `6ced9f68`: 36 938 string literals in `core/*/src` outside `#[cfg(test)]`, of which 11 are flagged
//! and all 11 are genuinely JavaScript -- zero false positives. Recall, measured by chunking 18 544
//! lines of the real hand-written JS this migration deleted (`core/*/src/js/*.js` at `4c0bee01`) into
//! pieces the size of a Rust string literal: 74.6 % of one-line pieces, 93.9 % of three-line, 97.4 % of
//! five-line, 99.2 % of twenty-line. The misses are pieces that are DATA rather than syntax -- a run of
//! `"name", "name",` inside an array, the middle of an object literal, or a line of closing braces --
//! which is the honest answer, because such a piece read alone is not JavaScript.

