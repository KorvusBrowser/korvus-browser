// The inventory.

#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
struct Entry {
    path: String,
    id: String,
    excerpt: String,
    line: usize,
}

fn repo_root() -> PathBuf {
    Path::new(WEBAPI).join("..").join("..").canonicalize().expect("repo root")
}

fn rs_files(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(rd) = std::fs::read_dir(dir) else { return };
    for e in rd.flatten() {
        let p = e.path();
        if p.is_dir() {
            rs_files(&p, out);
        } else if p.extension().and_then(|x| x.to_str()) == Some("rs") {
            out.push(p);
        }
    }
}

/// FNV-1a 64. An identity, not a digest: it names the exact bytes of a literal so that editing the
/// string retires its row and asks for the reason again.
fn fnv1a(s: &str) -> String {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for byte in s.as_bytes() {
        h ^= *byte as u64;
        h = h.wrapping_mul(0x0000_0100_0000_01b3);
    }
    format!("{h:016x}")[..12].to_string()
}

fn excerpt(s: &str) -> String {
    let flat: String = s
        .chars()
        .map(|c| match c {
            '\n' => '\u{2424}',
            '\t' | '\r' => ' ',
            c if (c as u32) < 0x20 => ' ',
            c => c,
        })
        .collect();
    let flat = flat.split_whitespace().collect::<Vec<_>>().join(" ");
    let flat = flat.replace('\u{2424}', "\\n");
    if flat.chars().count() > 90 {
        let cut: String = flat.chars().take(87).collect();
        format!("{cut}...")
    } else {
        flat
    }
}

/// Every JavaScript string literal in the kernel, sorted, as the manifest orders them.
fn detect() -> Vec<Entry> {
    let root = repo_root();
    let mut files = Vec::new();
    for d in SRC_DIRS {
        rs_files(&root.join(d), &mut files);
    }
    files.sort();
    let mut found = Vec::new();
    for f in &files {
        let rel = f.strip_prefix(&root).unwrap_or(f).to_string_lossy().replace('\\', "/");
        let src = std::fs::read_to_string(f).unwrap_or_default();
        for (line, text) in string_literals(&src) {
            if !js_markers(&text).is_empty() {
                found.push(Entry { path: rel.clone(), id: fnv1a(&text), excerpt: excerpt(&text), line });
            }
        }
    }
    found.sort();
    found
}

/// The manifest as `(path, id) -> (excerpt, reason)`, in file order.
fn read_manifest(path: &Path) -> BTreeMap<(String, String), (String, String)> {
    let mut out = BTreeMap::new();
    let Ok(text) = std::fs::read_to_string(path) else { return out };
    for line in text.lines() {
        if line.trim().is_empty() || line.starts_with('#') {
            continue;
        }
        let mut it = line.splitn(4, '\t');
        let (Some(p), Some(id), Some(ex), Some(reason)) = (it.next(), it.next(), it.next(), it.next()) else {
            continue;
        };
        out.insert((p.to_string(), id.to_string()), (ex.to_string(), reason.to_string()));
    }
    out
}

fn write_manifest(path: &Path, found: &[Entry], old: &BTreeMap<(String, String), (String, String)>) {
    let mut s = String::from(HEADER);
    for e in found {
        let reason = old
            .get(&(e.path.clone(), e.id.clone()))
            .map(|(_, r)| r.clone())
            .unwrap_or_else(|| NEEDS_REASON.to_string());
        s.push_str(&format!("{}\t{}\t{}\t{}\n", e.path, e.id, e.excerpt, reason));
    }
    std::fs::write(path, s).expect("write manifest");
}

#[test]
fn the_kernel_holds_no_unlisted_javascript() {
    let manifest = Path::new(WEBAPI).join(MANIFEST);
    let found = detect();
    let old = read_manifest(&manifest);

    if std::env::var(UPDATE_ENV).is_ok() {
        write_manifest(&manifest, &found, &old);
        eprintln!("wrote {} ({} entr{})", manifest.display(), found.len(), if found.len() == 1 { "y" } else { "ies" });
        return;
    }

    let listed: Vec<(String, String)> = old.keys().cloned().collect();
    let now: Vec<(String, String)> = found.iter().map(|e| (e.path.clone(), e.id.clone())).collect();

    let mut unlisted: Vec<&Entry> = found.iter().filter(|e| !listed.contains(&(e.path.clone(), e.id.clone()))).collect();
    unlisted.sort_by_key(|e| (e.path.clone(), e.line));
    let vanished: Vec<&(String, String)> = listed.iter().filter(|k| !now.contains(k)).collect();
    let unjustified: Vec<&(String, String)> = old.iter().filter(|(_, (_, r))| r.trim() == NEEDS_REASON || r.trim().is_empty()).map(|(k, _)| k).collect();

    let mut msg = String::new();
    if !unlisted.is_empty() {
        msg.push_str(&format!(
            "\n{} JavaScript string literal(s) in the kernel are NOT in {MANIFEST}:\n",
            unlisted.len()
        ));
        for e in &unlisted {
            msg.push_str(&format!("  {}:{}  [{}]\n      {}\n", e.path, e.line, js_markers_for(e).join(","), e.excerpt));
        }
        msg.push_str(
            "\n  The kernel defines Web API in one table per interface, in Rust -- not in a string.\n  \
             Put the member in its interface's table. If the string is\n  \
             genuinely not a Web-API definition, run\n\n      KORVUS_UPDATE_JS_STRINGS=1 cargo test -p korvus-webapi --test all -- js_strings::\n\n  \
             and replace REASON-REQUIRED with why it has to exist. An entry is a debt.\n",
        );
    }
    if !vanished.is_empty() {
        msg.push_str(&format!("\n{} row(s) in {MANIFEST} no longer match anything in the tree:\n", vanished.len()));
        for (p, id) in &vanished {
            let reason = old.get(&(p.clone(), id.clone())).map(|(_, r)| r.as_str()).unwrap_or("");
            msg.push_str(&format!("  {p}  {id}  -- {reason}\n"));
        }
        msg.push_str(
            "\n  GOOD NEWS, probably: a JS string left the kernel. Record the fall in the SAME commit --\n  \
             KORVUS_UPDATE_JS_STRINGS=1 cargo test -p korvus-webapi --test all -- js_strings::\n  \
             then scripts/freeze.sh --write-baseline, and commit both.\n",
        );
    }
    if !unjustified.is_empty() {
        msg.push_str(&format!("\n{} row(s) in {MANIFEST} still say {NEEDS_REASON}:\n", unjustified.len()));
        for (p, id) in &unjustified {
            msg.push_str(&format!("  {p}  {id}\n"));
        }
        msg.push_str("\n  Write why the string has to exist, in that row's last column.\n");
    }
    assert!(msg.is_empty(), "{msg}");
}

fn js_markers_for(e: &Entry) -> Vec<&'static str> {
    // Re-read the literal for its markers; the Entry carries only the excerpt.
    let root = repo_root();
    let src = std::fs::read_to_string(root.join(&e.path)).unwrap_or_default();
    for (line, text) in string_literals(&src) {
        if line == e.line && fnv1a(&text) == e.id {
            return js_markers(&text);
        }
    }
    Vec::new()
}

/// The manifest's excerpts must be the tree's, or a reader checking a reason against the wrong text
/// approves a row that says something else now.
#[test]
fn the_manifest_excerpts_match_the_tree() {
    if std::env::var(UPDATE_ENV).is_ok() {
        return;
    }
    let old = read_manifest(&Path::new(WEBAPI).join(MANIFEST));
    let found = detect();
    let mut stale = Vec::new();
    for e in &found {
        if let Some((ex, _)) = old.get(&(e.path.clone(), e.id.clone())) {
            if ex != &e.excerpt {
                stale.push(format!("  {}\n    manifest: {}\n    tree:     {}", e.path, ex, e.excerpt));
            }
        }
    }
    assert!(stale.is_empty(), "stale excerpt(s) in {MANIFEST}:\n{}", stale.join("\n"));
}

