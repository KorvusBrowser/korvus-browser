/// The regex `scripts/freeze.sh` rule 3 used, as a predicate. Kept here, in the test that replaced it,
/// so the claim "it caught neither" is checked by machine rather than asserted in prose.
fn old_rule_3(s: &str) -> bool {
    if s.contains("Object.defineProperty(") {
        return true;
    }
    let b = s.as_bytes();
    let mut from = 0;
    while let Some(rel) = s[from..].find("globalThis.") {
        let i = from + rel + "globalThis.".len();
        let mut j = i;
        if j < b.len() && b[j].is_ascii_uppercase() {
            j += 1;
            while j < b.len() && b[j].is_ascii_alphabetic() {
                j += 1;
            }
            let k = ws(b, j);
            if at(b, k, b'=') {
                return true;
            }
        }
        from = from + rel + 1;
    }
    false
}

