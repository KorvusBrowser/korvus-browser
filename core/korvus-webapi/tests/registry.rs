//! The exposure registry is load-bearing and its failure mode is SILENT.
//!
//! Native registration is collected by `build.rs` from each interface file's own `webapi_ops!` /
//! `webapi_objects!` declaration (see `binding/exposure.rs`). Dropping a declaration is **not a compile
//! error**: the crate builds, and the loss shows up only as Web-API members missing from the JS surface at
//! runtime. So the registered set is pinned -- but as a **manifest**, not as a count.
//!
//! `tests/fixtures/ops.manifest` lists every registered op, every cppgc object, and every declaring module,
//! sorted. This test regenerates that text from the live registry and diffs it. A lost declaration shows
//! up as NAMES missing from the live side; a new op shows up as names missing from the manifest. Either way
//! the diff says which, and fixing it is one command:
//!
//!     KORVUS_UPDATE_MANIFEST=1 cargo test -p korvus-webapi --test registry
//!
//! Until 2026-09-09 this file pinned four magic numbers (`OPS_AT_MIGRATION = 754` and friends)
//! that every op added anywhere had to bump on the same four lines -- the one file every parallel lane
//! collided on, and a pin that told you a count moved but not what. The narrative of how those counts rose
//! is in git history; the manifest carries the same guarantee with names.

use std::collections::BTreeSet;
use std::path::PathBuf;

use webapi::binding::exposure::{declaring_module_names, registered_op_names};

const MANIFEST: &str = "tests/fixtures/ops.manifest";

fn manifest_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(MANIFEST)
}

/// The manifest text the live registry produces right now.
fn current() -> String {
    let mut ops = registered_op_names();
    ops.sort_unstable();
    let op_mods = declaring_module_names();
    let mut out = String::new();
    out.push_str("# GENERATED by `KORVUS_UPDATE_MANIFEST=1 cargo test -p korvus-webapi --test registry` -- do not hand-edit.\n");
    out.push_str("# Every op / declaring module the webapi extension registers, sorted. tests/registry.rs\n");
    out.push_str("# diffs the live registry against this file; a `webapi_ops!` declaration lost in a refactor shows up here\n");
    out.push_str("# as names missing from the live side, a new op as names missing from the manifest.\n");
    for (section, items) in [("ops", ops), ("op-modules", op_mods.to_vec())] {
        out.push_str(&format!("\n[{section}]\n"));
        for i in items {
            out.push_str(i);
            out.push('\n');
        }
    }
    out
}

#[test]
fn the_live_registry_matches_its_manifest() {
    let path = manifest_path();
    let now = current();
    if std::env::var_os("KORVUS_UPDATE_MANIFEST").is_some() {
        std::fs::write(&path, &now).unwrap_or_else(|e| panic!("write {}: {e}", path.display()));
        return;
    }
    let want = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("read {} ({e}) -- run with KORVUS_UPDATE_MANIFEST=1 once", path.display()));
    if want == now {
        return;
    }
    let want_set: BTreeSet<&str> = want.lines().filter(|l| !l.starts_with('#')).collect();
    let now_set: BTreeSet<&str> = now.lines().filter(|l| !l.starts_with('#')).collect();
    let lost: Vec<&&str> = want_set.difference(&now_set).collect();
    let new: Vec<&&str> = now_set.difference(&want_set).collect();
    panic!(
        "the webapi registry differs from {MANIFEST}.\n  registered but NOT in the manifest (new declarations): {new:?}\n  in the manifest but NOT registered (LOST declarations -- members silently vanish from the JS surface): {lost:?}\nIf the change is intended: KORVUS_UPDATE_MANIFEST=1 cargo test -p korvus-webapi --test registry"
    );
}

/// AND THE BYTES GIT WILL COMMIT, not just the ones on disk.
///
/// `the_live_registry_matches_its_manifest` reads the WORKING TREE, so it is green the moment you
/// regenerate -- and stays green through a commit that records different bytes. That is not
/// hypothetical: the W11.5 merge staged an older `ops.manifest` with `git checkout --ours`, THEN
/// regenerated it, and committed the staged copy. HEAD carried 103 ops against a live registry of 15
/// and every gate run passed, because every gate run read the regenerated file beside them.
///
/// It is the same hole `scripts/sync.sh --check` closed for the five generated files --
/// the index is what `git commit` records -- and `ops.manifest` was outside that set because
/// `tools/sync` does not produce it. This closes it for the one derived fixture that was left.
///
/// THE INDEX IS JUDGED, AND HEAD IS NOT -- which I got wrong on the first attempt. A pre-commit gate
/// run sees HEAD as the PREVIOUS commit, so judging HEAD makes the check red on every legitimate
/// manifest change, which is a check people learn to skip. The index is what `git commit` records and
/// is exactly the copy the W11.5 merge got wrong. `scripts/sync.sh` splits the same way for the same
/// reason: `--check` judges tree + index, `--check-head` judges a committed ref on its own.
#[test]
fn the_manifest_git_will_commit_is_the_one_on_disk() {
    // CARGO_MANIFEST_DIR is the crate, two levels under the repo root.
    let repo = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent().and_then(|p| p.parent()).expect("repo root").to_path_buf();
    let rel = "core/korvus-webapi/tests/fixtures/ops.manifest";
    let disk = std::fs::read_to_string(repo.join(rel)).expect("read ops.manifest");
    {
        let (what, rev) = ("the index", "");
        let out = std::process::Command::new("git")
            .arg("-C").arg(&repo).arg("show").arg(format!("{rev}:{rel}"))
            .output();
        let Ok(out) = out else { return };
        if !out.status.success() {
            return; // not a git checkout, or the path is untracked -- nothing to compare
        }
        let recorded = String::from_utf8_lossy(&out.stdout);
        if recorded == disk {
            return;
        }
        let n = |s: &str| s.lines().filter(|l| l.starts_with("op_")).count();
        panic!(
            "ops.manifest in {what} is not the file on disk: {} ops recorded vs {} live.\n\
             These are the bytes a checkout gets. Regenerate and `git add` the result:\n  \
             KORVUS_UPDATE_MANIFEST=1 cargo test -p korvus-webapi --test all -- registry::",
            n(&recorded), n(&disk)
        );
    }
}

/// The registry must not double-register: two files declaring the same op would have been a duplicate
/// entry in the old hand list too, but the list was reviewable and this is generated.
#[test]
fn no_op_is_registered_twice() {
    let mut names = registered_op_names();
    names.sort_unstable();
    let before = names.len();
    names.dedup();
    assert_eq!(before, names.len(), "the same op name is registered by two different modules");
}

/// The manifest must actually carry something -- an empty file would make the first test vacuous.
///
/// The number here is a COLLAPSE FLOOR, not a pin: what an op count must be is pinned by name, above,
/// against the manifest (invariant I5), and this only refuses a registry that has evaporated. It has to
/// stay well under the real total, because the goal drives that total DOWN -- every JS glue file
/// deleted takes its `op_*` builders with it. It read `> 700` until W5.1 L7 deleted `dom/08e-indexeddb.js`
/// and the 63 `op_req_*` / `op_db_*` / `op_tx_*` / `op_store_*` / `op_index_*` / `op_cursor_*` /
/// `op_kr_*` / `op_idb_*` builders that existed only to hand those callbacks to it (722 -> 659), and
/// `> 400` until W5.1 L9 (49 `op_range_*` / `op_sel_*`) and W5.1 L14 (19 `op_hl_*`) together took the
/// live count to 393 -- MEASURED, not estimated. The floor follows the total down; it does not hold it
/// up, because the exact answer is the by-name diff above and this only catches evaporation.
///
/// `> 250` until five later commits deleted the 91 ops of the DOM
/// traversal, CharacterData/Text, Node, `core/dom/shared.rs`-macro and straggler families, taking the
/// live count 278 -> 187 -- MEASURED by regenerating the manifest at each step, not estimated. Every
/// one was an `#[op2]` wrapper handing a raw callback to JS by name; the `interface!` row that mounts
/// the member names that callback directly, so the wrapper was a door onto a room with another way in.
/// The floor is lowered ahead of them so that each of those commits is green on its own.
///
/// THE FLOOR IS RUNNING OUT OF ROOM, and the next unit to lower it should read this. W11.1 measured
/// that of the ops registered at its base only FOUR are reached by anything at all --
/// `op_bc_deliver_external`, `op_mp_remote`, `op_port_deliver_external`, `op_subresource_fetch` --
/// and the two sibling units of this campaign are deleting most of what W11.6 leaves. An absolute
/// floor cannot tell "correctly emptied" from "evaporated" once the true answer is single digits, so
/// when it next blocks a legitimate deletion, REPLACE it rather than halving it again: the honest
/// successor is "the four reached ops are all present", which a collapsed registry cannot satisfy
/// and which needs no revision after the next sweep.
#[test]
fn the_manifest_is_not_empty() {
    let now = current();

    // THE COLLAPSE FLOOR IS RETIRED. It read `> 250`, then 194, 150, 120 as three
    // units of one campaign each lowered it against their own measured count -- and at the merge of
    // the second it finally blocked a legitimate deletion, which is the condition the comment above
    // said to replace it on rather than halve it a fifth time.
    //
    // An absolute floor cannot distinguish "correctly emptied" from "evaporated" once the true answer
    // is single digits, and it is: of every op this registry has ever held, FOUR are reached by
    // anything at all. So the check is now those four by name. A collapsed registry cannot satisfy it,
    // it needs no revision after the next sweep, and -- unlike a number -- it says what it is
    // protecting. If one of these four legitimately goes, delete its line here in the same commit and
    // say what replaced it; that is a fact about the engine, not a tolerance.
    for op in ["op_bc_deliver_external", "op_mp_remote", "op_port_deliver_external", "op_subresource_fetch"] {
        assert!(
            now.lines().any(|l| l.trim() == op),
            "{op} is missing from the manifest -- it is one of the four ops anything in this tree \
             actually reaches, so the registry has collapsed rather than been emptied"
        );
    }
    // (It also required an `[objects]` section: the cppgc classes registered with deno_core. A later change
    // made every class an own class and deleted that half of the registry, so the manifest has none.)
    assert!(!now.contains("\n[objects]\n"), "an `[objects]` section is back: nothing registers a deno_core class any more");
}
